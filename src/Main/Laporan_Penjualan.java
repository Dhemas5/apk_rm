private void showDateChooser() {
        JDialog dialog = new JDialog();
        dialog.setTitle("Pilih Tanggal");
        dialog.setModal(true);
        dialog.setDefaultCloseOperation(JDialog.DISPOSE_ON_CLOSE);

        // Inisialisasi JDateChooser
        JDateChooser dateChooser = new JDateChooser();
        dateChooser.setDateFormatString("yyyy-MM-dd");

        // Batasi tanggal hingga hari ini (27 Mei 2025, 06:56 PM WIB)
        dateChooser.setMaxSelectableDate(new Date(System.currentTimeMillis()));

        // Jika txt_tanggal sudah memiliki nilai, set tanggal awal di JDateChooser
        try {
            String tanggalStr = txt_tanggal.getText().trim();
            if (!tanggalStr.isEmpty() && tanggalStr.matches("\\d{4}-\\d{2}-\\d{2}")) {
                SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
                dateChooser.setDate(dateFormat.parse(tanggalStr));
            }
        } catch (ParseException e) {
            Logger.getLogger(Laporan_Penjualan.class.getName()).log(Level.SEVERE, null, e);
        }

        // Tombol OK untuk konfirmasi
        JButton btnOk = new JButton("OK");
        btnOk.setBackground(new Color(46, 204, 113)); // Warna hijau
        btnOk.setForeground(Color.WHITE);
        btnOk.addActionListener(e -> {
            if (dateChooser.getDate() != null) {
                SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
                txt_tanggal.setText(dateFormat.format(dateChooser.getDate()));
                isDataLoaded = false; // Reset status saat tanggal berubah
            }
            dialog.dispose();
        });

        // Tombol Batal untuk membatalkan
        JButton btnCancel = new JButton("Batal");
        btnCancel.setBackground(new Color(231, 76, 60)); // Warna merah
        btnCancel.setForeground(Color.WHITE);
        btnCancel.addActionListener(e -> dialog.dispose());

        // Panel untuk layout
        JPanel panel = new JPanel(new BorderLayout());
        panel.setBorder(BorderFactory.createEmptyBorder(10, 10, 10, 10)); // Padding
        panel.add(dateChooser, BorderLayout.CENTER);

        // Panel untuk tombol
        JPanel buttonPanel = new JPanel(new FlowLayout(FlowLayout.RIGHT));
        buttonPanel.add(btnOk);
        buttonPanel.add(btnCancel);
        panel.add(buttonPanel, BorderLayout.SOUTH);

        dialog.add(panel);
        dialog.pack(); // Menyesuaikan ukuran awal berdasarkan konten
        dialog.setSize(300, 150); // Atur lebar (300px) dan tinggi (200px) secara manual
        dialog.setLocationRelativeTo(null); // Posisikan di tengah
        dialog.setVisible(true);
    }

