    public void getData(Date tanggal, int startIndex, int entriesPage, DefaultTableModel model) {
        model.setRowCount(0);

        try {
            String sql = "SELECT tr.ID_Transaksi, tr.Tanggal_Transaksi, p.Nama_Pelanggan, tr.Total, "
                    + "u.Nama_User, m.Nomor_Meja "
                    + "FROM tbl_transaksi tr "
                    + "INNER JOIN tbl_pelanggan p ON tr.ID_Pelanggan = p.ID_Pelanggan "
                    + "INNER JOIN tbl_user u ON tr.ID_User = u.ID_User "
                    + "INNER JOIN tbl_meja m ON tr.ID_Meja = m.ID_Meja "
                    + "WHERE DATE(tr.Tanggal_Transaksi) = ? "
                    + "ORDER BY tr.Tanggal_Transaksi DESC LIMIT ?, ?";

            try (PreparedStatement st = con.prepareStatement(sql)) {
                st.setDate(1, new java.sql.Date(tanggal.getTime()));
                st.setInt(2, startIndex);
                st.setInt(3, entriesPage);

                ResultSet rs = st.executeQuery();

                int no = startIndex + 1;
                while (rs.next()) {
                    Object[] rowData = {
                        rs.getString("ID_Transaksi"),
                        rs.getString("Tanggal_Transaksi"),
                        rs.getString("Nama_Pelanggan"),
                        rs.getString("Total"),
                        rs.getString("Nama_User"),
                        rs.getString("Nomor_Meja")
                    };
                    model.addRow(rowData);

                }
            }
        } catch (SQLException e) {
            Logger.getLogger(Laporan_Penjualan.class
                    .getName()).log(Level.SEVERE, null, e);
        }
    }

    private void searchData() {
        String tanggalStr = txt_tanggal.getText().trim();
        if (tanggalStr.isEmpty() || !tanggalStr.matches("\\d{4}-\\d{2}-\\d{2}")) {
            JOptionPane.showMessageDialog(null, "Silakan pilih tanggal terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String kataKunci = txt_search.getText();
        DefaultTableModel model = (DefaultTableModel) tbl_data.getModel();
        model.setRowCount(0);

        try {
            SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
            Date tanggal = dateFormat.parse(tanggalStr);
            String sql = "SELECT tr.ID_Transaksi, tr.Tanggal_Transaksi, p.Nama_Pelanggan, tr.Total, "
                    + "u.Nama_User, m.Nomor_Meja "
                    + "FROM tbl_transaksi tr "
                    + "INNER JOIN tbl_pelanggan p ON tr.ID_Pelanggan = p.ID_Pelanggan "
                    + "INNER JOIN tbl_user u ON tr.ID_User = u.ID_User "
                    + "INNER JOIN tbl_meja m ON tr.ID_Meja = m.ID_Meja "
                    + "WHERE (p.Nama_Pelanggan LIKE ? OR tr.ID_Transaksi LIKE ? OR u.Nama_User LIKE ?) "
                    + "AND DATE(tr.Tanggal_Transaksi) = ? "
                    + "ORDER BY tr.Tanggal_Transaksi DESC";

            try (PreparedStatement st = con.prepareStatement(sql)) {
                st.setString(1, "%" + kataKunci + "%");
                st.setString(2, "%" + kataKunci + "%");
                st.setString(3, "%" + kataKunci + "%");
                st.setDate(4, new java.sql.Date(tanggal.getTime()));
                ResultSet rs = st.executeQuery();

                while (rs.next()) {
                    Object[] rowData = {
                        rs.getString("ID_Transaksi"),
                        rs.getString("Tanggal_Transaksi"),
                        rs.getString("Nama_Pelanggan"),
                        rs.getString("Total"),
                        rs.getString("Nama_User"),
                        rs.getString("Nomor_Meja")
                    };
                    model.addRow(rowData);
                }

                // Periksa apakah hasil pencarian kosong
                if (model.getRowCount() == 0) {
                    JOptionPane.showMessageDialog(null, "Tidak ada data yang sesuai dengan pencarian untuk tanggal ini!", "Informasi", JOptionPane.INFORMATION_MESSAGE);
                }
            }
        } catch (SQLException | ParseException e) {
            Logger.getLogger(Laporan_Penjualan.class.getName()).log(Level.SEVERE, null, e);
            JOptionPane.showMessageDialog(null, "Gagal melakukan pencarian: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void cetakLaporan() {
        String tanggalStr = txt_tanggal.getText().trim();
        if (tanggalStr.isEmpty() || !tanggalStr.matches("\\d{4}-\\d{2}-\\d{2}")) {
            JOptionPane.showMessageDialog(null, "Silakan pilih tanggal terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!isDataLoaded) {
            JOptionPane.showMessageDialog(null, "Silakan tampilkan data terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String reportPath = "src/Report/Laporan_Penjualan.jasper";
        try {
            File file = new File(reportPath);
            if (!file.exists()) {
                JasperCompileManager.compileReportToFile("src/Report/Laporan_Penjualan.jrxml", reportPath);
            }

            SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
            dateFormat.setLenient(false);
            Date tanggal = dateFormat.parse(tanggalStr);
            System.out.println("Tanggal yang dikirim: " + tanggal);

            HashMap<String, Object> parameters = new HashMap<>();
            parameters.put("tanggal", tanggal);

            if (con == null || con.isClosed()) {
                throw new Exception("Koneksi database tidak valid atau telah ditutup");
            }

            JasperPrint print = JasperFillManager.fillReport(reportPath, parameters, con);
            JasperViewer viewer = new JasperViewer(print, false);
            viewer.setExtendedState(JasperViewer.MAXIMIZED_BOTH);
            viewer.setVisible(true);
        } catch (ParseException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Format tanggal salah. Gunakan format yyyy-MM-dd.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (JRException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Gagal mengisi laporan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Gagal mencetak laporan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void setPendapatan() {
        PreparedStatement pst = null;
        ResultSet rs = null;
        try {
            String tanggalStr = txt_tanggal.getText().trim();
            if (tanggalStr.isEmpty() || !tanggalStr.matches("\\d{4}-\\d{2}-\\d{2}")) {
                Pendapatan.setText("Rp 0");
                return;
            }
            SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
            Date tanggal = dateFormat.parse(tanggalStr);
            String sql = "SELECT SUM(Total) AS total_pendapatan FROM tbl_transaksi WHERE DATE(Tanggal_Transaksi) = ?";
            pst = con.prepareStatement(sql);
            pst.setDate(1, new java.sql.Date(tanggal.getTime()));

            rs = pst.executeQuery();
            if (rs.next()) {
                double totalPendapatan = rs.getDouble("total_pendapatan");
                if (rs.wasNull()) {
                    totalPendapatan = 0.0;
                }
                Pendapatan.setText("Rp " + String.format("%,.0f", totalPendapatan));
            } else {
                Pendapatan.setText("Rp 0");
            }
        } catch (SQLException | ParseException e) {
            e.printStackTrace();
            Pendapatan.setText("Error!");
            JOptionPane.showMessageDialog(this, "Gagal menghitung pendapatan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (pst != null) {
                    pst.close();
                }
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
        }
    }
