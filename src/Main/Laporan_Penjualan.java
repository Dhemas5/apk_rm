    private int getTotalData() {
        int totalData = 0;
        String tanggalStr = txt_tanggal.getText().trim();
        if (tanggalStr.isEmpty() || !tanggalStr.matches("\\d{4}-\\d{2}-\\d{2}")) {
            return 0; // Kembalikan 0 jika tanggal tidak valid
        }

        try {
            SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
            Date tanggal = dateFormat.parse(tanggalStr);
            String sql = "SELECT COUNT(*) AS total FROM tbl_transaksi WHERE DATE(Tanggal_Transaksi) = ?";
            try (PreparedStatement st = con.prepareStatement(sql)) {
                st.setDate(1, new java.sql.Date(tanggal.getTime()));
                ResultSet rs = st.executeQuery();
                if (rs.next()) {
                    totalData = rs.getInt("total");
                }
            }
        } catch (SQLException | ParseException e) {
            Logger.getLogger(Laporan_Penjualan.class.getName()).log(Level.SEVERE, null, e);
            JOptionPane.showMessageDialog(this, "Gagal menghitung total data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
        return totalData;
    }

    private void calculateTotalPages() {
        int totalData = getTotalData();
        totalpages = (int) Math.ceil((double) totalData / DataperHalaman);
    }

