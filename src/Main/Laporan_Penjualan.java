    private void load() {
        String tanggalStr = txt_tanggal.getText().trim();
        if (tanggalStr.isEmpty() || !tanggalStr.matches("\\d{4}-\\d{2}-\\d{2}")) {
            // Hanya tampilkan pesan validasi jika dipicu oleh aksi pengguna (misalnya, tombol Tampilkan)
            if (isDataLoaded) {
                JOptionPane.showMessageDialog(null, "Silakan pilih tanggal terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            }
            return;
        }

        calculateTotalPages();
        int totalData = getTotalData();
        lb_halaman.setText("Halaman " + HalamanSaatIni + " dari Total Data " + totalData);

        int startIndex = (HalamanSaatIni - 1) * DataperHalaman;
        SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");

        try {
            Date tanggal = dateFormat.parse(tanggalStr);
            DefaultTableModel model = (DefaultTableModel) tbl_data.getModel();
            getData(tanggal, startIndex, DataperHalaman, model);

            // Periksa apakah data kosong
            if (model.getRowCount() == 0) {
                JOptionPane.showMessageDialog(null, "Tidak ada data untuk tanggal ini!", "Informasi", JOptionPane.INFORMATION_MESSAGE);
                Pendapatan.setText("Rp 0");
                return;
            }

            setPendapatan();
        } catch (ParseException e) {
            JOptionPane.showMessageDialog(null, "Format tanggal tidak valid! Gunakan format yyyy-MM-dd.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

