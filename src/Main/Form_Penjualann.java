    private void updateData() {
        int selectedRow = tbl_data_sementara.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data yang ingin diubah", "Peringatan", JOptionPane.WARNING_MESSAGE);
            System.out.println("Tidak ada baris yang dipilih untuk diubah");
            return;
        }

        String idMenu = tbl_data_sementara.getValueAt(selectedRow, 1).toString(); // Ambil ID_Menu dari kolom 1
        String jumlahStr = txt_jumlah.getText().trim();
        if (jumlahStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Masukkan jumlah yang valid", "Peringatan", JOptionPane.WARNING_MESSAGE);
            System.out.println("Jumlah kosong untuk ID_Menu: " + idMenu);
            return;
        }

        int jumlahBeli;
        try {
            jumlahBeli = Integer.parseInt(jumlahStr);
            if (jumlahBeli <= 0) {
                JOptionPane.showMessageDialog(this, "Jumlah harus lebih dari 0", "Peringatan", JOptionPane.WARNING_MESSAGE);
                System.out.println("Jumlah tidak valid: " + jumlahStr);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Jumlah harus berupa angka", "Error", JOptionPane.ERROR_MESSAGE);
            System.out.println("Format jumlah tidak valid: " + jumlahStr);
            return;
        }

        int harga = 0;
        try {
            String sql = "SELECT Harga FROM tbl_sementara WHERE ID_Menu = ?";
            try (PreparedStatement st = con.prepareStatement(sql)) {
                st.setString(1, idMenu);
                ResultSet rs = st.executeQuery();
                if (rs.next()) {
                    harga = rs.getInt("Harga");
                } else {
                    JOptionPane.showMessageDialog(this, "Harga tidak ditemukan untuk ID_Menu: " + idMenu, "Error", JOptionPane.ERROR_MESSAGE);
                    System.out.println("Harga tidak ditemukan untuk ID_Menu: " + idMenu);
                    return;
                }
            }
        } catch (SQLException e) {
            System.out.println("SQLException saat mengambil harga: " + e.getMessage());
            Logger.getLogger(Form_Penjualann.class.getName()).log(Level.SEVERE, "Gagal mengambil harga", e);
            JOptionPane.showMessageDialog(this, "Gagal mengambil harga: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int subTotal = jumlahBeli * harga;
        System.out.println("Mencoba memperbarui ID_Menu: " + idMenu + ", Jumlah: " + jumlahBeli + ", Sub_Total: " + subTotal);

        try {
            String sql = "UPDATE tbl_sementara SET Jumlah_Beli = ?, Sub_Total = ? WHERE ID_Menu = ?";
            try (PreparedStatement st = con.prepareStatement(sql)) {
                st.setInt(1, jumlahBeli);
                st.setInt(2, subTotal);
                st.setString(3, idMenu);
                int rowsUpdated = st.executeUpdate();
                if (rowsUpdated > 0) {
                    System.out.println("Berhasil memperbarui ID_Menu: " + idMenu + ", Baris terpengaruh: " + rowsUpdated);
                    JOptionPane.showMessageDialog(this, "Data berhasil diperbarui", "Sukses", JOptionPane.INFORMATION_MESSAGE);
                    loadDataSementara();
                    lb_total_beli2.setText(String.format("%.0f", getTotalHarga()));
                    btn_ubah.setText("");
                    btn_hapus.setVisible(false);
                    btn_cancel_sementara.setVisible(false);
                    txt_barcode.setText("");
                    txt_jumlah.setText("");
                    txt_barcode.requestFocus();
                } else {
                    System.out.println("Gagal memperbarui: Tidak ada baris yang sesuai dengan ID_Menu " + idMenu);
                    JOptionPane.showMessageDialog(this, "Gagal memperbarui data: Data tidak ditemukan", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (SQLException e) {
            System.out.println("SQLException saat memperbarui data: " + e.getMessage());
            Logger.getLogger(Form_Penjualann.class.getName()).log(Level.SEVERE, "Gagal memperbarui data", e);
            JOptionPane.showMessageDialog(this, "Gagal memperbarui data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

