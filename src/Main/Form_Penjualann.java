    private void insertDataSementara(String idMenu, String barcode, String namaMenu, int harga, boolean isEdit) {
        if (idMenu == null || idMenu.trim().isEmpty() || barcode == null || barcode.trim().isEmpty()
                || namaMenu == null || namaMenu.trim().isEmpty() || harga <= 0) {
            System.out.println("Validasi gagal: ID_Menu=" + idMenu + ", Barcode=" + barcode
                    + ", Nama_Menu=" + namaMenu + ", Harga=" + harga);
            JOptionPane.showMessageDialog(this, "Data menu tidak valid", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String jumlah = txt_jumlah.getText().trim().isEmpty() ? "1" : txt_jumlah.getText().trim();
        int jumlahBeli;
        try {
            jumlahBeli = Integer.parseInt(jumlah);
            if (jumlahBeli <= 0) {
                System.out.println("Jumlah tidak valid: " + jumlah);
                JOptionPane.showMessageDialog(this, "Jumlah harus lebih dari 0", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            System.out.println("Format jumlah tidak valid: " + jumlah);
            JOptionPane.showMessageDialog(this, "Jumlah tidak valid", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            String checkSql = "SELECT Jumlah_Beli, Sub_Total FROM tbl_sementara WHERE ID_Menu = ?";
            try (PreparedStatement checkSt = con.prepareStatement(checkSql)) {
                checkSt.setString(1, idMenu);
                ResultSet rs = checkSt.executeQuery();
                if (rs.next()) {
                    // Update existing record
                    int newJumlah = isEdit ? jumlahBeli : rs.getInt("Jumlah_Beli") + jumlahBeli;
                    int newSubTotal = newJumlah * harga;

                    String updateSql = "UPDATE tbl_sementara SET Jumlah_Beli = ?, Sub_Total = ?, Barcode = ? WHERE ID_Menu = ?";
                    try (PreparedStatement updateSt = con.prepareStatement(updateSql)) {
                        updateSt.setInt(1, newJumlah);
                        updateSt.setInt(2, newSubTotal);
                        updateSt.setString(3, barcode);
                        updateSt.setString(4, idMenu);
                        int rowsUpdated = updateSt.executeUpdate();
                        System.out.println("Updated ID_Menu: " + idMenu + ", Jumlah baru: " + newJumlah + ", Rows affected: " + rowsUpdated);
                    }
                } else {
                    // Insert new record
                    int subTotal = jumlahBeli * harga;
                    String insertSql = "INSERT INTO tbl_sementara (ID_Menu, Barcode, Nama_Menu, Harga, Jumlah_Beli, Sub_Total) VALUES (?, ?, ?, ?, ?, ?)";
                    try (PreparedStatement insertSt = con.prepareStatement(insertSql)) {
                        insertSt.setString(1, idMenu);
                        insertSt.setString(2, barcode);
                        insertSt.setString(3, namaMenu);
                        insertSt.setInt(4, harga);
                        insertSt.setInt(5, jumlahBeli);
                        insertSt.setInt(6, subTotal);
                        int rowsInserted = insertSt.executeUpdate();
                        System.out.println("Inserted ID_Menu: " + idMenu + ", Barcode: " + barcode + ", Rows affected: " + rowsInserted);
                    }
                }
            }
            loadDataSementara();
            lb_total_beli2.setText(String.format("%.0f", getTotalHarga()));
        } catch (SQLException e) {
            System.out.println("SQLException saat menambahkan data sementara: " + e.getMessage());
            Logger.getLogger(Form_Penjualann.class.getName()).log(Level.SEVERE, "Gagal menambahkan data sementara", e);
            JOptionPane.showMessageDialog(this, "Gagal menambahkan menu: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

