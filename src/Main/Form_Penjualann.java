    private void calculateKembalian() {
        try {
            String totalStr = lb_total_beli2.getText().replaceAll("[^\\d]", "");
            if (totalStr.isEmpty()) {
                txt_kembalian.setText("0");
                return;
            }
            int total = Integer.parseInt(totalStr);

            String bayarStr = txt_bayar.getText().trim();
            if (bayarStr.isEmpty()) {
                txt_kembalian.setText("0");
                return;
            }
            int bayar = Integer.parseInt(bayarStr);

            int kembali = bayar - total;
            txt_kembalian.setText(String.valueOf(kembali >= 0 ? kembali : 0));
        } catch (NumberFormatException e) {
            txt_kembalian.setText("0");
        }
    }

    public void insertData() {
        String idTransaksi = lb_ID.getText().trim();
        String tanggal = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss").format(new Date());
        double total = getTotalHarga();
        double bayar;
        try {
            bayar = txt_bayar.getText().trim().isEmpty() ? 0 : Double.parseDouble(txt_bayar.getText().trim());
        } catch (NumberFormatException e) {
            System.out.println("Invalid bayar input: " + txt_bayar.getText());
            JOptionPane.showMessageDialog(this, "Jumlah bayar tidak valid", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        double kembalian = bayar - total;
        String catatan = txt_catatan.getText().trim();

        if (idTransaksi.isEmpty()) {
            System.out.println("Validation failed: idTransaksi is empty");
            JOptionPane.showMessageDialog(this, "ID Transaksi tidak valid!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (IdPelanggan.isEmpty() || cbx_pelanggan.getSelectedItem().toString().equals("Pilih Pelanggan")) {
            System.out.println("Validation failed: IdPelanggan is empty or not selected");
            JOptionPane.showMessageDialog(this, "Pilih pelanggan terlebih dahulu!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (IdMeja.isEmpty() || cbx_meja.getSelectedItem().toString().equals("Pilih Meja")) {
            System.out.println("Validation failed: IdMeja is empty or not selected");
            JOptionPane.showMessageDialog(this, "Pilih meja terlebih dahulu!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (total == 0) {
            System.out.println("Validation failed: Total is zero");
            JOptionPane.showMessageDialog(this, "Belum ada item transaksi!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (kembalian < 0) {
            System.out.println("Validation failed: Insufficient payment");
            JOptionPane.showMessageDialog(this, "Jumlah bayar tidak mencukupi!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (userID == null || userID.trim().isEmpty()) {
            System.out.println("Validation failed: userID is null or empty");
            JOptionPane.showMessageDialog(this, "Pengguna tidak teridentifikasi! Silakan login terlebih dahulu.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            String sql = "INSERT INTO tbl_transaksi (ID_Transaksi, Tanggal_Transaksi, ID_Pelanggan, ID_User, ID_Meja, Total, Bayar, Kembalian, Catatan) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)";
            try (PreparedStatement st = con.prepareStatement(sql)) {
                st.setString(1, idTransaksi);
                st.setString(2, tanggal);
                st.setString(3, IdPelanggan);
                st.setString(4, userID);
                st.setString(5, IdMeja);
                st.setDouble(6, total);
                st.setDouble(7, bayar);
                st.setDouble(8, kembalian);
                st.setString(9, catatan);
                int rowInserted = st.executeUpdate();

                if (rowInserted > 0) {
                    System.out.println("Insert successful, inserting detail transaksi");
                    insertDetailTransaksi(idTransaksi);
                    hapusDataSementara();
                    JOptionPane.showMessageDialog(this, "Transaksi berhasil disimpan", "Sukses", JOptionPane.INFORMATION_MESSAGE);

                    int confirm = JOptionPane.showConfirmDialog(this, "Apakah Anda ingin mencetak nota?", "Konfirmasi Cetak", JOptionPane.YES_NO_OPTION);
                    if (confirm == JOptionPane.YES_OPTION) {
                        System.out.println("ID Transaksi untuk print: " + idTransaksi);
                        printLaporan(idTransaksi);
                    } else {
                        resetForm();
                        loadData();
                        showPanel();
                    }
                } else {
                    System.out.println("Insert failed: No rows affected");
                    JOptionPane.showMessageDialog(this, "Gagal menyimpan transaksi", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (SQLException e) {
            System.out.println("SQL Error in insertData: " + e.getMessage());
            Logger.getLogger(Form_Penjualann.class.getName()).log(Level.SEVERE, null, e);
            JOptionPane.showMessageDialog(this, "Gagal menyimpan transaksi: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

