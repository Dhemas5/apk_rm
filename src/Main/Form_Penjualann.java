    private void getData(int startIndex, int entriesPage, DefaultTableModel model) {
        model.setRowCount(0);
        try {
            String sql = "SELECT tr.ID_Transaksi, tr.Tanggal_Transaksi, tr.Total, tr.Bayar, tr.Kembalian, tr.Catatan, "
                    + "plgn.Nama_Pelanggan, usr.Nama_User, mj.Nomor_Meja "
                    + "FROM tbl_transaksi tr "
                    + "INNER JOIN tbl_pelanggan plgn ON plgn.ID_Pelanggan = tr.ID_Pelanggan "
                    + "INNER JOIN tbl_user usr ON usr.ID_User = tr.ID_User "
                    + "INNER JOIN tbl_meja mj ON mj.ID_Meja = tr.ID_Meja "
                    + "ORDER BY tr.ID_Transaksi ASC LIMIT ? OFFSET ?";
            try (PreparedStatement st = con.prepareStatement(sql)) {
                st.setInt(1, entriesPage);
                st.setInt(2, startIndex);
                ResultSet rs = st.executeQuery();
                int no = startIndex + 1;
                while (rs.next()) {
                    Object[] rowData = {
                        no++,
                        rs.getString("ID_Transaksi"),
                        rs.getString("Tanggal_Transaksi"),
                        rs.getString("Nama_Pelanggan"),
                        rs.getString("Nama_User"),
                        rs.getString("Nomor_Meja"),
                        String.format("%.0f", rs.getDouble("Total")),
                        String.format("%.0f", rs.getDouble("Bayar")),
                        String.format("%.0f", rs.getDouble("Kembalian")),
                        rs.getString("Catatan") != null ? rs.getString("Catatan") : ""
                    };
                    model.addRow(rowData);
                }
            }
        } catch (SQLException e) {
            Logger.getLogger(Form_Penjualann.class.getName()).log(Level.SEVERE, null, e);
            JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private String setIDTransaksi() throws SQLException {
        String urutan;
        SimpleDateFormat noFormat = new SimpleDateFormat("yyMM");
        String no = noFormat.format(new Date());
        String sql = "SELECT RIGHT(ID_Transaksi, 3) AS Nomor FROM tbl_transaksi WHERE ID_Transaksi LIKE ? ORDER BY ID_Transaksi DESC LIMIT 1";
        try (PreparedStatement st = con.prepareStatement(sql)) {
            st.setString(1, no + "%");
            ResultSet rs = st.executeQuery();
            if (rs.next()) {
                int nomor = Integer.parseInt(rs.getString("Nomor")) + 1;
                urutan = no + String.format("%03d", nomor);
            } else {
                urutan = no + "001";
            }
        }
        if (urutan == null || urutan.trim().isEmpty()) {
            throw new SQLException("Gagal menghasilkan ID Transaksi");
        }
        lb_ID.setText(urutan);
        lb_ID.setEnabled(false);
        System.out.println("Generated ID_Transaksi: " + urutan);
        return urutan;
    }

